export function toPrompt(da: Da, locale: Locale, format: DaFormat): string {
  const { universe } = da;
  const { colors, type, motion, layout, texture } = resolve(da);
  const note =
    locale === "fr"
      ? "# Prompt en anglais : les modèles d'image et de vidéo le suivent mieux."
      : "# Paste into an image or video model.";
  const frame =
    format === "video"
      ? "Vertical 9:16 motion graphic for a short social video"
      : "Website hero section, 16:9, with room for a headline on the left";
  return `# DA ${universe.name.en} · ${da.code}
${note}

${frame}: ${universe.prompt.subject}.
Style: ${universe.prompt.style}.
Palette: ${colors.bg} background, ${colors.surface} surfaces, ${colors.accent} accent, ${colors.accent2} secondary, ${colors.glow} glow, ${colors.ink} highlights.
Type feel: ${FONT_FEEL[type.display.font]} titles, ${FONT_FEEL[type.accent.font]} accents.
Texture: ${daTextures[texture].name.en.toLowerCase()}. Motion: ${motion.cut.en.charAt(0).toLowerCase()}${motion.cut.en.slice(1)} Spring entrances, ${motion.bpm} BPM.
Composition: ${layout.cue.en.charAt(0).toLowerCase()}${layout.cue.en.slice(1)}

Negative prompt: logos, trademarks, recognisable characters, official game or film assets, watermark, garbled text, extra fingers.
`;
}

export function exportText(id: DaExportId, da: Da, locale: Locale, format: DaFormat): string {
  if (id === "css") return toCss(da, locale);
  if (id === "tokens") return toTokens(da, locale);
  if (id === "skill") return toSkill(da, locale);
  return toPrompt(da, locale, format);
}

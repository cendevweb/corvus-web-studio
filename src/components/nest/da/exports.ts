const fmt = (value: number, locale: Locale, digits = 1) =>
  value.toLocaleString(locale === "fr" ? "fr-FR" : "en-GB", { maximumFractionDigits: digits });

/** French puts a space before a colon and uses « » quotes; English does neither. */
const colon = (locale: Locale) => (locale === "fr" ? " :" : ":");
const quote = (text: string, locale: Locale) => (locale === "fr" ? `« ${text} »` : `“${text}”`);

const family = (role: DaTypeRole) => {
  const font = DA_FONTS[role.font];
  return `"${font.name}", ${font.fallback}`;
};

/** Google Fonts CSS API URL for the faces a DA uses. */
export function googleFontsUrl(da: Da): string {
  const { type } = resolve(da);
  const used = new Map<DaFontId, DaTypeRole[]>();
  for (const role of [type.display, type.body, type.accent]) used.set(role.font, [...(used.get(role.font) ?? []), role]);
  const families = [...used].map(([id, roles]) => {
    const font = DA_FONTS[id];
    const name = font.name.replace(/ /g, "+");
    if (font.google === "static") return `family=${name}`;
    if (font.google === "width") {
      const tuples = [...new Set(roles.map((role) => `${role.width ?? 100},${role.weight}`))].sort();
      return `family=${name}:wdth,wght@${tuples.join(";")}`;
    }
    const weights = [...new Set(roles.map((role) => role.weight))].sort((a, b) => a - b);
    return `family=${name}:wght@${weights.join(";")}`;
  });
  return `https://fonts.googleapis.com/css2?${families.join("&")}&display=swap`;
}


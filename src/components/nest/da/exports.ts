export function toCss(da: Da, locale: Locale): string {
  const c = colon(locale);
  const q = (text: string) => quote(text, locale);
  const t = T[locale];
  const { universe } = da;
  const { palette, colors, type, motion, layout, texture, grain, radius } = resolve(da);
  const spring = springCurve(motion.spring);
  const beat = 60 / motion.bpm;
  const pad = (name: string) => name.padEnd(19);
  const ratio = (role: DaRole) => fmt(contrast(colors[role], colors.bg), locale);
  const display = type.display;
  const accent = type.accent;

  return `/* DA ${q(universe.name[locale])} · ${da.code}
   ${t.generated}
   ${t.evokes}${c} ${universe.ref[locale]}
   (${t.noAssets}) */
@import url("${googleFontsUrl(da)}");

:root {
  /* ${t.palette} ${q(palette.name[locale])} */
${DA_ROLES.map((role) => `  ${pad(`--da-${role === "accent2" ? "accent-2" : role}:`)} ${colors[role]}; /* ${t.roles[role]}${role === "ink" || role === "accent" ? ` · ${ratio(role)}:1 ${t.onBg}` : ""} */`).join("\n")}

  /* ${t.type} ${q(type.name[locale])} */
  ${pad("--da-font-display:")} ${family(display)};
  ${pad("--da-font-body:")} ${family(type.body)};
  ${pad("--da-font-accent:")} ${family(accent)};

  /* ${t.motion} ${q(motion.name[locale])} · ${motion.bpm} BPM */
  ${pad("--da-ease:")} ${cubic(motion.ease)};
  ${pad("--da-spring:")} ${springToLinear(spring)};
  ${pad("--da-dur-in:")} ${motion.durations.in}ms;
  ${pad("--da-dur-out:")} ${motion.durations.out}ms;
  ${pad("--da-stagger:")} ${motion.durations.stagger}ms;
  ${pad("--da-beat:")} ${beat.toFixed(3)}s;

  ${pad("--da-on-accent:")} ${readableOn(colors.accent, [colors.ink, colors.bg, "#FFFFFF", "#111111"])}; /* ${t.onAccent} */
  ${pad("--da-ink-rgb:")} ${rgb(colors.ink)};

  ${pad("--da-radius:")} ${radius}px;
  ${pad("--da-grain:")} ${grain};
}

body {
  background: var(--da-bg);
  color: var(--da-ink);
  font: ${type.body.weight} 1rem/1.55 var(--da-font-body);${type.body.width && type.body.width !== 100 ? `\n  font-stretch: ${type.body.width}%;` : ""}
}

.da-title {
  font-family: var(--da-font-display);
  font-weight: ${display.weight};${display.width && display.width !== 100 ? `\n  font-stretch: ${display.width}%;` : ""}
  text-transform: ${display.upper ? "uppercase" : "none"};
  letter-spacing: ${display.tracking ?? 0}em;
  line-height: .95;
}

.da-accent {
  font-family: var(--da-font-accent);
  font-weight: ${accent.weight};${accent.upper ? "\n  text-transform: uppercase;" : ""}${accent.tracking ? `\n  letter-spacing: ${accent.tracking}em;` : ""}
  color: var(--da-accent);
}

.da-button {
  background: var(--da-accent);
  color: var(--da-on-accent);
  border-radius: var(--da-radius);
  transition: transform var(--da-dur-out) var(--da-ease);
}
.da-button:active { transform: scale(.96); }

/* ${t.captions}${c} <p class="da-caption"><span style="--i: 0">…</span> <span class="hl" style="--i: 1">…</span></p> */
${CAPTION_CSS[type.caption]}
.da-caption > span {
  display: inline-block;
  animation: da-pop var(--da-dur-in) var(--da-spring) both;
  animation-delay: calc(var(--i, 0) * var(--da-stagger));
}
@keyframes da-pop { from { opacity: 0; transform: translateY(.4em) scale(.9); } }

/* ${t.signature}${c} ${motion.name[locale]}. ${SIGNATURE_NOTE[motion.signature][locale]} */
${SIGNATURE_CSS[motion.signature]}

/* ${t.texture}${c} ${daTextures[texture].name[locale]} (${t.grain} ${grain}) · ${t.layout}${c} ${layout.name[locale]} */
.da-grain { position: relative; isolation: isolate; }
.da-grain::after {
  content: "";
  position: absolute;
  inset: 0;
  pointer-events: none;
  opacity: var(--da-grain);
  mix-blend-mode: overlay;
  background-image: ${GRAIN_SVG};
}

/* ${t.reduced} */
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation: none !important; transition: none !important; }
}
`;
}

/* ───────── Design tokens (W3C Design Tokens Format) ───────── */

export function toTokens(da: Da, locale: Locale): string {
  const q = (text: string) => quote(text, locale);
  const t = T[locale];
  const { universe } = da;
  const { colors, type, motion, texture, grain, radius, layout } = resolve(da);
  const font = (role: DaTypeRole) => {
    const f = DA_FONTS[role.font];
    return [f.name, ...f.fallback.split(",").map((part) => part.trim().replace(/"/g, ""))];
  };
  const ms = (value: number) => ({ $type: "duration", $value: { value, unit: "ms" } });
  const tokens = {
    $description: `DA ${q(universe.name[locale])} · ${da.code} · ${t.generated}`,
    color: Object.fromEntries(
      DA_ROLES.map((role) => [role, { $type: "color", $value: colors[role], $description: t.roles[role] }]),
    ),
    font: {
      display: { $type: "fontFamily", $value: font(type.display) },
      body: { $type: "fontFamily", $value: font(type.body) },
      accent: { $type: "fontFamily", $value: font(type.accent) },
    },
    fontWeight: {
      display: { $type: "fontWeight", $value: type.display.weight },
      body: { $type: "fontWeight", $value: type.body.weight },
      accent: { $type: "fontWeight", $value: type.accent.weight },
    },
    motion: {
      ease: { $type: "cubicBezier", $value: [...motion.ease] },
      in: ms(motion.durations.in),
      out: ms(motion.durations.out),
      stagger: ms(motion.durations.stagger),
      beat: ms(Math.round(60000 / motion.bpm)),
    },
    radius: { $type: "dimension", $value: { value: radius, unit: "px" } },
    $extensions: {
      "studio.corvus.da": {
        universe: universe.id,
        code: da.code,
        reference: universe.ref[locale],
        bpm: motion.bpm,
        spring: { stiffness: motion.spring.stiffness, damping: motion.spring.damping, mass: motion.spring.mass ?? 1 },
        signature: motion.signature,
        texture,
        grain,
        caption: type.caption,
        layout: { site: layout.site, video: layout.video },
      },
    },
  };
  return `${JSON.stringify(tokens, null, 2)}\n`;
}


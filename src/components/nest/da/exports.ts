const roleLine = (role: DaTypeRole, s: (typeof SKILL)[Locale]) =>
  [
    `${DA_FONTS[role.font].name} ${role.weight}`,
    role.upper ? s.upper : null,
    role.tracking ? `${s.tracking} ${role.tracking} em` : null,
    role.width && role.width !== 100 ? `${s.width} ${role.width} %` : null,
  ]
    .filter(Boolean)
    .join(", ");

export function toSkill(da: Da, locale: Locale): string {
  const c = colon(locale);
  const q = (text: string) => quote(text, locale);
  const t = T[locale];
  const s = SKILL[locale];
  const { universe } = da;
  const { palette, colors, type, motion, layout, texture, grain, hookIndex } = resolve(da);
  const spring = springCurve(motion.spring);
  const seconds = loopSeconds(motion.bpm);
  const frames = Math.round(seconds * 30);
  const beatFrames = Math.round((60 / motion.bpm) * 30);
  const hook = universe.hooks[locale][hookIndex]!;
  const words = parseLine(hook);
  const keyword = words.find((word) => word.hl)?.text.replace(/[.,:;!?…]+$/, "") ?? words[0]!.text;
  const ref = universe.ref[locale].split(" · ")[0]!.split(",")[0]!;
  const name = `da-${universe.id}-${da.code.toLowerCase()}`;
  const card = universe.card;

  return `---
name: ${name}
description: ${s.describe(universe.name[locale], da.code, ref)}
---

# DA ${universe.name[locale]} · ${da.code}

${s.reference}${c} ${universe.ref[locale]}.
${s.rule}${c} ${s.never}

${universe.why[locale]}

${s.keywords}${c} ${universe.keywords[locale].join(", ")}.

## ${t.palette} ${q(palette.name[locale])}

| ${t.role} | ${t.color} | ${t.usage} |
| --- | --- | --- |
${DA_ROLES.map((role) => `| ${t.roles[role]} | \`${colors[role]}\` | ${t.uses[role]}${role === "ink" || role === "accent" ? ` (${fmt(contrast(colors[role], colors.bg), locale)}:1 ${t.onBg})` : ""} |`).join("\n")}

## ${t.type} ${q(type.name[locale])}

- ${s.titles}${c} ${roleLine(type.display, s)}.
- ${s.body}${c} ${roleLine(type.body, s)}.
- ${s.accent}${c} ${roleLine(type.accent, s)}.
- ${s.caption}${c} ${CAPTION_NAME[type.caption][locale]}.

## ${t.texture}

- ${daTextures[texture].name[locale]} (${t.grain} ${grain})${c} ${daTextures[texture].note[locale].toLowerCase()}.

## ${t.motion} ${q(motion.name[locale])}

- ${s.loop(motion.bpm, fmt(seconds, locale))}
- ${s.spring(motion.spring.stiffness, motion.spring.damping, fmt(spring.duration, locale, 2), fmt((spring.peak - 1) * 100, locale, 0))}
- ${s.ui(cubic(motion.ease), motion.durations.in, motion.durations.out, motion.durations.stagger)}
- ${s.cut}${c} ${motion.cut[locale]}
- ${s.transitions}${c} ${motion.transitions[locale].join(", ")}.

## ${t.layout} ${q(layout.name[locale])}

- ${layout.cue[locale]}
- ${s.safe}

## ${s.video}

\`\`\`tsx
${s.comment(motion.bpm, frames)}
const BEAT = ${beatFrames};
const pop = (frame: number, fps: number, i: number) =>
  spring({ frame: frame - i * ${Math.max(1, Math.round((motion.durations.stagger / 1000) * 30))}, fps, config: { stiffness: ${motion.spring.stiffness}, damping: ${motion.spring.damping}, mass: 1 } });
\`\`\`

${s.scenes}${c}

1. ${s.hook} (${s.beats(0, 4)})${c} ${q(words.map((word) => word.text).join(" "))}, ${s.wordByWord(keyword)}.
2. ${s.demo} (${s.beats(4, 8)})${c} ${s.card} ${q(card.title[locale])}${c} ${card.rows[locale].join(" · ")}.
3. ${s.signature} (${s.beats(8, 12)})${c} ${motion.name[locale]}, ${q(`${universe.sig.title[locale]} · ${universe.sig.sub[locale]}`)}.
4. ${s.cta} (${s.beats(12, 16)})${c} ${q(universe.cta[locale])}.

## ${s.site}

- ${s.siteLayout(layout.name[locale], layout.cue[locale])}
- ${s.cssNote(exportFile(da, "css"))}

## ${s.sound}

${universe.sound[locale].map((line) => `- ${line}`).join("\n")}

## ${s.do}

${universe.do[locale].map((line) => `- ${line}`).join("\n")}

## ${s.dont}

${universe.dont[locale].map((line) => `- ${line}`).join("\n")}
- ${s.never}
`;
}


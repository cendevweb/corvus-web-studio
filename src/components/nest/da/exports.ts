/**
 * The four exports of a DA: CSS custom properties (the preview runs on the same values), design
 * tokens in the W3C format, a Claude skill (SKILL.md) and a prompt for image and video models.
 */

export type DaExportId = "css" | "tokens" | "skill" | "prompt";
export const DA_EXPORTS: readonly DaExportId[] = ["css", "tokens", "skill", "prompt"];

export function exportFile(da: Da, id: DaExportId): string {
  const slug = `da-${da.universe.id}-${da.code.toLowerCase()}`;
  if (id === "css") return `${slug}.css`;
  if (id === "tokens") return `${slug}.tokens.json`;
  if (id === "skill") return "SKILL.md";
  return `${slug}-prompt.txt`;
}

export const exportMime = (id: DaExportId): string =>
  id === "css" ? "text/css" : id === "tokens" ? "application/json" : id === "skill" ? "text/markdown" : "text/plain";

